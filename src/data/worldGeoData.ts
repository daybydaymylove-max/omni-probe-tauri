// 3. 球面大圆航线 (Great Circle Arc) 高精路标插值算法
//    严禁任何前端静态造假，所有真实通讯节点由后端引擎驱动
// =========================================================================
/**
 * 在球面上计算两经纬度点之间的球面大圆航线中间采样点集
 * @param src 起点坐标
 * @param dst 终点坐标
 * @param numPoints 采样点数量 (推荐 30~40 点)
 * @returns 沿大圆切线分布的经纬度点集数组
 */
export function interpolateGreatCircle(src: GeoCoord, dst: GeoCoord, numPoints = 32): GeoCoord[] {
  const p1Lat = (src.lat * Math.PI) / 180;
  const p1Lon = (src.lon * Math.PI) / 180;
  const p2Lat = (dst.lat * Math.PI) / 180;
  const p2Lon = (dst.lon * Math.PI) / 180;

  // 球面角距离 delta
  const cosD = Math.sin(p1Lat) * Math.sin(p2Lat) + Math.cos(p1Lat) * Math.cos(p2Lat) * Math.cos(p2Lon - p1Lon);
  const d = Math.acos(Math.max(-1, Math.min(1, cosD)));

  if (d < 1e-4) {
    return [src, dst];
  }

  const sinD = Math.sin(d);
  const waypoints: GeoCoord[] = [];

  for (let i = 0; i <= numPoints; i++) {
    const f = i / numPoints;
    const a = Math.sin((1 - f) * d) / sinD;
    const b = Math.sin(f * d) / sinD;

    const x = a * Math.cos(p1Lat) * Math.cos(p1Lon) + b * Math.cos(p2Lat) * Math.cos(p2Lon);
    const y = a * Math.cos(p1Lat) * Math.sin(p1Lon) + b * Math.cos(p2Lat) * Math.sin(p2Lon);
    const z = a * Math.sin(p1Lat) + b * Math.sin(p2Lat);

    const lat = Math.atan2(z, Math.sqrt(x * x + y * y)) * (180 / Math.PI);
    const lon = Math.atan2(y, x) * (180 / Math.PI);

    waypoints.push({
      lat: Math.round(lat * 100) / 100,
      lon: Math.round(lon * 100) / 100,
    });
  }

  return waypoints;
}

/**
 * 计算大圆航线真实物理距离 (km)
 */
export function calculateGreatCircleDistanceKm(src: GeoCoord, dst: GeoCoord): number {
  const R = 6371.0; // 地球平均半径 km
  const dLat = ((dst.lat - src.lat) * Math.PI) / 180;
  const dLon = ((dst.lon - src.lon) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((src.lat * Math.PI) / 180) * Math.cos((dst.lat * Math.PI) / 180) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c);
}

/**
 * 基于光纤折射率 (n ≈ 1.468, 真空光速 300,000 km/s) 计算理论光纤双向往返时延 (RTT ms)
 */
export function calculateTheoreticalFiberRtt(distanceKm: number): number {
  const speedInFiber = 204.0; // km / ms (约 204,000 km/s)
  // 双向往返: 2 * distance / speed
  const rtt = (2 * distanceKm) / speedInFiber;
  return Math.round(rtt * 10) / 10;
}
